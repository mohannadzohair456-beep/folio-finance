const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const html=fs.readFileSync('android/app/src/main/assets/index.html','utf8');
const upgrade=fs.readFileSync('android/app/src/main/assets/folio-v2.js','utf8');
const inline=html.match(/<script>([\s\S]*?)<\/script>/);assert.ok(inline);
const storage=new Map();
const elements=new Map();
const body={classList:{add(){},remove(){}},appendChild(){}};
const doc={body,createElement(){return {innerHTML:'',remove(){}}},getElementById(id){if(id==='v2-overlay')return null;if(!elements.has(id))elements.set(id,{innerHTML:'',value:'',focus(){}});return elements.get(id)}};
const sandbox={window:{scrollTo(){}},document:doc,localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,String(v))},console,setTimeout:()=>1,setInterval:()=>1,clearTimeout(){},confirm:()=>true};
sandbox.window=sandbox;sandbox.scrollTo=()=>{};
const context=vm.createContext(sandbox);
new vm.Script(inline[1]).runInContext(context);
new vm.Script(upgrade).runInContext(context);
assert.ok(doc.getElementById('root').innerHTML.includes('Meet Folio.'),'Onboarding appears first');
vm.runInContext('FolioV2.nextStep()',context);
assert.ok(doc.getElementById('root').innerHTML.includes('Make it yours.'),'Financial setup step');
for(const [id,v] of [['onb-balance','20000'],['onb-income','15000'],['onb-budget','5000']])doc.getElementById(id).value=v;
vm.runInContext('FolioV2.nextStep()',context);
assert.equal(JSON.parse(storage.get('folio_finance_v1')).reportedBalanceMinor,2000000);
vm.runInContext('FolioV2.nextStep();FolioV2.markReady();nav("assistant")',context);
assert.ok(doc.getElementById('root').innerHTML.includes('Ask Folio'),'Assistant page works');
assert.equal(JSON.parse(storage.get('folio_finance_v1')).monthlyBudgetMinor,500000,'Onboarding monthly budget saved');
vm.runInContext('nav("overview")',context);
assert.ok(doc.getElementById('root').innerHTML.includes('Monthly spending target'),'Overall budget reflected on home');
vm.runInContext('nav("budgets")',context);
assert.ok(doc.getElementById('root').innerHTML.includes('Overall spending target'),'Overall budget reflected on Budgets');
vm.runInContext('nav("assistant")',context);
const v=context.window.FolioV2;
assert.equal(v.detectAmount('20 thousand pounds'),20000,'spoken large amount');
assert.equal(v.detectAmount('٢٠ ألف جنيه'),20000,'Arabic Egyptian bank amount');
assert.equal(v.planCommand('مرتبي ١٥ ألف جنيه').action.type,'incomePlan','Arabic voice salary');
assert.equal(v.planCommand('دفعت ٢٠٠ جنيه في مطعم').action.type,'expense','Arabic voice expense');
assert.equal(v.planCommand('Can I afford 3000?').action,undefined,'Affordability does not write automatically');
assert.equal(v.planCommand('I spent 200 on coffee').action.type,'expense');
assert.equal(v.planCommand('My salary is 15000').action.type,'incomePlan');
doc.getElementById('folio-assistant-input').value='I spent 200 on coffee';
vm.runInContext('FolioV2.submitText();FolioV2.applyDraft()',context);
assert.equal(JSON.parse(storage.get('folio_finance_v1')).transactions.length,1,'Reviewed expense stored');
assert.equal(JSON.parse(storage.get('folio_finance_v1')).transactions[0].amountMinor,20000);
assert.ok(!html.includes('demoNotice()}'+ '$'+'{trackingPanel()}<div class="metrics">'),'Tracking diagnostics removed from home');
console.log('PASS Folio onboarding + assistant smoke tests');
